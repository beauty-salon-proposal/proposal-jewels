export function resolveFile(pathname, search) {
  const cands = PAGES.filter((p) => p.route === pathname)
  if (!cands.length) return null
  const exact = cands.find((p) => p.search === search)
  return (exact || cands.find((p) => !p.search) || cands[0]).file
}
export function hrefToRoute(href, curFile) {
  if (!href || /^(https?:|mailto:|tel:|javascript:|#|data:)/i.test(href)) return null
  const clean = href.split('#')[0].split('?')[0]
  if (!clean.endsWith('.html')) return null
  const base = curFile.slice('mirror/'.length)
  const slash = base.lastIndexOf('/')
  const dir = slash >= 0 ? base.slice(0, slash + 1) : ''
  let rel = clean.startsWith('/') ? clean.slice(1)
    : clean.startsWith('./') ? dir + clean.slice(2) : dir + clean
  const parts = []
  for (const seg of rel.split('/')) {
    if (seg === '..') parts.pop()
    else if (seg !== '.') parts.push(seg)
  }
  rel = parts.join('/')
  const hit = PAGES.find((p) => p.file === 'mirror/' + rel)
  if (hit) return hit.route + hit.search
  return '/mirror/' + rel
}
